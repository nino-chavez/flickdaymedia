/**
 * Sting wordmark — the locked Peridot wordmark as eight registered PNG layers,
 * one letter each, for motion/wordmark-sting.
 *
 * Every layer is the full mark's canvas holding one letter's ink, cropped with
 * the full mark's own trim box. Stacked, the eight redraw the mark exactly
 * (checked below); apart, each letter can grow and collapse about its own
 * centre. PNG for the same reason as the site wordmark (BRAND-PRIORS.md):
 * Peridot is licensed for live text, not for embedded outlines, and the
 * HyperFrames render then needs no font kit.
 *
 * Wordmark only: no play mark (nino, 2026-10-12; the symbol and lockup gates
 * are still open).
 *
 * Needs network (the Adobe Fonts kit) and ImageMagick (`magick`).
 *
 *   node scripts/build-sting-wordmark.mjs
 *     → motion/wordmark-sting/assets/wordmark/letter-{1..8}.png, layers.js
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';
import { chromium, PNG_STABLE, shootMark, WORD, YELLOW } from './wordmark-lib.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'motion', 'wordmark-sting', 'assets', 'wordmark');
// Twice the 800 px the sting shows, so the build's overshoot never upscales.
const WIDTH = 1600;
// Share of pixels where the stacked layers may differ from the one-piece
// render: only where two letters' antialiased edges overlap (k|d is kerned
// tight). A layer shifted 4 px measured 0.0077, fifteen times this.
const MAX_STRAY = 0.0005;

const magick = (...args) => execFileSync('magick', args).toString().trim();

async function main() {
  mkdirSync(OUT, { recursive: true });
  const tmp = mkdtempSync(join(tmpdir(), 'flickday-sting-'));
  const browser = await chromium.launch().catch(() => chromium.launch({ channel: 'chrome' }));
  console.log(`browser: ${browser.version()}`);
  try {
    const page = await browser.newPage({ deviceScaleFactor: 2 });

    // The full mark sets the crop every layer shares.
    const fullRaw = join(tmp, 'full-raw.png');
    await shootMark(page, tmp, YELLOW, fullRaw);
    const box = magick(fullRaw, '-format', '%@', 'info:');
    const full = join(tmp, 'full.png');
    magick(fullRaw, '-crop', box, '+repage', '-resize', `${WIDTH}x`, full);
    const [W, H] = magick(full, '-format', '%w %h', 'info:').split(' ').map(Number);

    const letters = [];
    for (const [i, ch] of [...WORD].entries()) {
      const raw = join(tmp, `raw-${i}.png`);
      await shootMark(page, tmp, YELLOW, raw, i);
      const file = `letter-${i + 1}.png`;
      const out = join(OUT, file);
      magick(raw, '-crop', box, '+repage', '-resize', `${WIDTH}x`, ...PNG_STABLE, out);
      // The letter's ink box inside the shared canvas, as the transform-origin
      // the sting scales it about.
      const [w, h, x, y] = magick(out, '-format', '%@', 'info:').match(/\d+/g).map(Number);
      // One letter's ink, not none and not two: a ligature or a shaping change
      // empties one layer and doubles another, and the stacked check below
      // cannot see that, since the pair still draws.
      if (!w || !h || w > W / 4) throw new Error(`${file} holds ${w}x${h} of ink, not one letter '${ch}'`);
      const pct = (n, d) => `${((n / d) * 100).toFixed(2)}%`;
      letters.push({ ch, src: `assets/wordmark/${file}`, origin: `${pct(x + w / 2, W)} ${pct(y + h / 2, H)}` });
      console.log(`✓ ${file}  ${ch}  ink ${w}x${h}+${x}+${y}`);
    }

    // Registration gate: all eight stacked must redraw the one-piece mark.
    const stacked = join(tmp, 'stacked.png');
    magick(...letters.map((l) => join(OUT, l.src.split('/').pop())), '-background', 'none', '-flatten', stacked);
    // -compare reports AE as a share of all pixels, not a count.
    const share = Number(magick(full, stacked, '-alpha', 'on', '-fuzz', '10%', '-metric', 'AE', '-compare', '-format', '%[distortion]', 'info:'));
    console.log(`stacked vs one-piece: ${(share * 100).toFixed(3)}% of pixels differ past 10%`);
    if (share > MAX_STRAY) throw new Error(`layers do not redraw the mark (${(share * 100).toFixed(3)}% differ); refusing to keep them`);

    writeFileSync(
      join(OUT, 'layers.js'),
      `// Generated by scripts/build-sting-wordmark.mjs. Do not edit by hand.\n` +
        `window.FLICKDAY_WORDMARK = ${JSON.stringify({ width: W, height: H, letters }, null, 2)};\n`,
    );
    console.log(`✓ layers.js  ${W}x${H}`);
  } finally {
    await browser.close();
    rmSync(tmp, { recursive: true, force: true });
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
